import assert from 'node:assert/strict';
import {validateReplyActions} from '../src/reply-actions.js';
const text=value=>({type:'text',text:value,resourceId:null});
const sticker=id=>({type:'sticker',text:null,resourceId:id});
const generated={type:'generatedImage',text:null,resourceId:null};
const waves=id=>({type:'wavesImage',text:null,resourceId:id});
const output=replyActions=>({protocolVersion:2,replyActions,memoryOps:[],stickerNotes:[],replyTo:'-1',imagePrompt:'',imageSourceMessageId:null});
const options={replyMode:'natural',stickers:[{id:'yes'},{id:'laugh'}],gameAssets:new Map([['game1',{}]]),messageIds:new Set(['-1']),imageMode:'auto',imageSources:new Map([['-1',[{}]]])};
assert.deepEqual(validateReplyActions(output([text('啊？'),sticker('laugh'),text('你还挺能吹')]),options).actions.map(a=>a.type),['text','sticker','text']);
assert.equal(validateReplyActions(output([]),options).actions.length,0);
assert.throws(()=>validateReplyActions({reply:'old',memoryOps:[]},options),/协议|格式/);
assert.throws(()=>validateReplyActions({...output([text('不能先发')]),memoryOps:[null]},options),/协议/);
assert.throws(()=>validateReplyActions({...output([text('不能先发')]),stickerNotes:[null]},options),/协议/);
assert.throws(()=>validateReplyActions(output([text('先别发'),sticker('unknown')]),options),/表情/);
assert.throws(()=>validateReplyActions(output([sticker('yes'),sticker('yes')]),options),/重复/);
assert.throws(()=>validateReplyActions(output(Array.from({length:5},()=>text('不刷屏'))),options),/文字/);
assert.throws(()=>validateReplyActions(output([text('一'),text('二')]),{...options,replyMode:'single'}),/单段/);
assert.throws(()=>validateReplyActions(output([waves('foreign')]),options),/鸣潮/);
assert.throws(()=>validateReplyActions(output([generated]),options),/生图/);
assert.throws(()=>validateReplyActions({...output([generated]),imagePrompt:'猫'}, {...options,imageMode:'off'}),/关闭/);
assert.throws(()=>validateReplyActions({...output([generated]),imagePrompt:'改图',imageSourceMessageId:'999'},options),/参考图/);
assert.throws(()=>validateReplyActions({...output([text('引用')]),replyTo:'foreign'},options),/引用/);
assert.throws(()=>validateReplyActions(output([{...text('危险'),target:'group:2'}]),options),/动作/);
assert.deepEqual(validateReplyActions({...output([generated,waves('game1')]),imagePrompt:'猫'},options).actions.map(a=>a.type),['generatedImage','wavesImage']);
console.log('PASS strict ordered reply contract, silence, legacy rejection, all-before-send resource validation, action bounds and scoped references');
