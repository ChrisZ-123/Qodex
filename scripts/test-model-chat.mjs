import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {ModelChat} from '../src/model-chat.js';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'qq-model-test-'));
const prompts=[],sent=[],cancelled=[];let seq=0;
const allow=new Set(['group:1','group:2','private:3']);
const api={sessions:{create:async()=>({result:{ok:true,value:{sessionId:'s'+(++seq)}}}),prompt:async p=>{prompts.push(p);return {result:{ok:true,value:{}}}}},stopSessionWork:async id=>cancelled.push(id)};
const options={dir,api,allowed:k=>allow.has(k),send:async(k,t)=>sent.push([k,t]),persona:()=>({name:'猫娘',content:'喵'})};
const chat=new ModelChat({...options,legacy:{sessions:{'group:1':'old'},conversations:{'group:1':{recentMessages:[{sender:'甲',text:'旧历史',time:100000}]}}}});
const message=text=>({sender:'群友',text,time:'2026-09-23T00:00:00Z'});
const done=async(key,reply,status='completed')=>{const sid=chat.entry(key).sessionId;await chat.consume(sid,{type:'assistant/message',data:{message:{content:[{type:'text',text:reply}]}}});await chat.consume(sid,{type:'turn/end',data:{reason:{kind:status}}});};
await chat.receive('group:9',message('越权'));
assert.equal(prompts.length,0);assert(!chat.entries.has('group:9'));
await chat.receive('group:1',message('没有 @ 也要阅读'));assert.equal(prompts.length,1);assert.equal(prompts[0].context.earlierMessages[0].text,'旧历史');
await chat.receive('group:1',message('排队甲'));await chat.receive('group:1',message('排队乙'));
await chat.receive('group:2',message('另一个群'));assert.equal(prompts.length,2);assert.notEqual(prompts[0].sessionId,prompts[1].sessionId);
await done('group:1','[不回复]');await new Promise(r=>setImmediate(r));assert.equal(sent.length,0);assert.equal(prompts.length,3);assert.deepEqual(JSON.parse(prompts[2].content[0].text).messages.map(x=>x.text),['排队甲','排队乙']);
await done('group:1','正常回复\n原样保留');assert.deepEqual(sent[0],['group:1','正常回复\n原样保留']);
allow.delete('group:2');await done('group:2','不应发出');assert.equal(sent.length,1);
await chat.receive('private:3',message('管理员私聊'));await chat.pause(true);await chat.pause(false);await done('private:3','暂停前的过期回复');assert.equal(sent.length,1);assert(cancelled.length>0);
await chat.pause(true);await chat.receive('group:1',message('暂停只记录'));assert.equal(prompts.length,4);await chat.pause(false);
chat.send=async()=>{throw Error('transport failed')};await chat.receive('group:1',message('发送错误'));await done('group:1','失败回复');assert.equal(chat.entry('group:1').messages.at(-1).kind,'error');
const restored=new ModelChat(options);assert.equal(restored.entry('group:1').legacySessionId,'old');assert.equal(restored.entry('group:1').sessionId,chat.entry('group:1').sessionId);assert(restored.history('group:1').messages.some(m=>m.text==='旧历史'));
assert.throws(()=>restored.history('../secret'));
allow.add('group:4');
let release;
const oldCreate=api.sessions.create;
api.sessions.create=()=>new Promise(r=>release=r);
const racing=chat.receive('group:4',message('建会话期间暂停'));
await chat.pause(true);await chat.pause(false);
const count=prompts.length;
release(await oldCreate());await racing;assert.equal(prompts.length,count);
fs.rmSync(dir,{recursive:true,force:true});
console.log('PASS all-message delivery, multiple isolated groups, history migration, silence, batching, revoked access, pause race and send failure');
