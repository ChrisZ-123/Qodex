import assert from 'node:assert/strict';
import {prepareStickerLearning,applyVisualNotes} from '../src/sticker-learning.js';
import {normalizeStickerEntry,mergeStickerLibrary} from '../src/sticker-lib.js';
const entries=['a','b','c'].map(id=>normalizeStickerEntry({id,url:`https://example.org/${id}`,md5:id,updatedAt:'initial'}));
const image={type:'image',mediaType:'image/png',data:'fixture'};
const prep=await prepareStickerLearning(entries,async()=>image);
assert.deepEqual(prep.snapshots.map(s=>s.id),['a','b']);assert.equal(prep.images.filter(i=>i.type==='image').length,2);
const notes=[{id:'a',note:'笑脸，表达开心'},{id:'b',note:'惊讶'},{id:'c',note:'没看过不能记'}];
const learned=applyVisualNotes(entries,prep.snapshots,notes);assert.equal(learned.learned,2);assert.equal(learned.entries[2].localNote,'');
assert.equal((await prepareStickerLearning(learned.entries,async()=>image)).snapshots[0].id,'c');
const manual=entries.map(e=>e.id==='a'?{...e,localNote:'管理员备注'}:e);
assert.equal(applyVisualNotes(manual,prep.snapshots,notes).entries[0].localNote,'管理员备注');
assert.equal(applyVisualNotes(entries.map(e=>({...e,url:'changed'})),prep.snapshots,notes).learned,0);
const failed=await prepareStickerLearning(entries,async()=>{throw Error('download');});
const blocked=applyVisualNotes(entries,[],[],failed.failures).entries;
assert.equal(blocked[0].learningError.length>0,true);
assert.deepEqual((await prepareStickerLearning(blocked,async()=>image)).snapshots.map(s=>s.id),['c']);
const synced=mergeStickerLibrary(learned.entries,entries.map(e=>({emoji_id:e.id,url:e.url})));
assert.equal(synced[0].localNote,'笑脸，表达开心');assert.equal(synced[0].noteSource,'model');
console.log('PASS bounded visual input, image identity, manual priority, persistent notes and explicit retry');
